-- Backfill the volunteer roster from the retired `src/data/volunteers.ts`.
--
-- 94 volunteers across 8 historical seasons, generated from the file
-- it replaces. Group membership is unknown for these rows and stays null.
--
-- Idempotent: every statement ends in ON CONFLICT DO NOTHING, so re-running it
-- is safe. Apply after 0010.

-- ---------------------------------------------------------------------------
-- Historical seasons become cohorts.
--
-- The dates are the real start and end of each season, as recorded in 季度管理.
-- They also make listCohorts (starts_at desc, nulls last) sort these archives
-- below the live mentorship seasons; bulletin_open is false because they are
-- archives, not live boards.
--
-- `cohorts.name` carries no unique constraint, so ON CONFLICT DO NOTHING would
-- not stop a second run from creating eight duplicate seasons. NOT EXISTS does.
-- ---------------------------------------------------------------------------
insert into public.cohorts (name, starts_at, ends_at, bulletin_open)
select source.name, source.starts_at, source.ends_at, false
from (values
  ('2020冬季', date '2020-10-17', date '2021-01-17'),
  ('2021夏季', date '2021-08-01', date '2021-08-31'),
  ('2022夏季', date '2022-07-31', date '2022-10-01'),
  ('2022春季', date '2022-02-04', date '2022-04-10'),
  ('2023秋季', date '2023-08-14', date '2023-11-12'),
  ('2024冬季', date '2024-11-10', date '2025-01-27'),
  ('2024春季', date '2024-04-05', date '2024-07-07'),
  ('2025夏季', date '2025-07-07', date '2025-09-07')
) as source (name, starts_at, ends_at)
where not exists (
  select 1 from public.cohorts c
  where lower(btrim(c.name)) = lower(source.name)
);

